using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace RoslynBridge.Extension;

internal static class DeclarationExtensions
{
    extension(SyntaxNode node)
    {
        /// <summary>
        /// True for the nodes that can hold a type or member declaration. Method bodies hold none.
        /// </summary>
        public bool HoldsDeclarations =>
            node
                is CompilationUnitSyntax
                    or BaseNamespaceDeclarationSyntax
                    or TypeDeclarationSyntax
                    or BaseFieldDeclarationSyntax
                    or VariableDeclarationSyntax;

        /// <summary>
        /// True for the nodes that declare a type, a member or a variable.
        /// </summary>
        public bool IsDeclaration =>
            node
                is BaseTypeDeclarationSyntax
                    or DelegateDeclarationSyntax
                    or BaseMethodDeclarationSyntax
                    or BasePropertyDeclarationSyntax
                    or VariableDeclaratorSyntax;

        /// <summary>
        /// The field declaration of its only variable, so that removing the range leaves valid code.
        /// </summary>
        public SyntaxNode WholeDeclaration =>
            node
                is VariableDeclaratorSyntax
                {
                    Parent: VariableDeclarationSyntax
                    {
                        Variables.Count: 1,
                        Parent: BaseFieldDeclarationSyntax fieldDeclaration,
                    },
                }
                ? fieldDeclaration
                : node;

        /// <summary>
        /// True for a file whose leading comment marks it as generated, as tools write it.
        /// </summary>
        public bool HasGeneratedHeader =>
            node.GetLeadingTrivia()
                .Any(trivia =>
                    (
                        trivia.IsKind(SyntaxKind.SingleLineCommentTrivia)
                        || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)
                    )
                    && trivia
                        .ToString()
                        .Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)
                );
    }
}
